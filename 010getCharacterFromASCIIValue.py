# chr() - you may need to determine the character that corresponds to a given code point. In this situation, you can use the built-in chr() function

def get_char(c):
    return chr(c)

print(get_char(65))#'A'
print(get_char(33))#'!'
print(get_char(34))#'"'
print(get_char(35))#'#'
print(get_char(36))#'$'
print(get_char(37))#'%'
print(get_char(38))#'&'